        verticalAlignment = Alignment.CenterVertically
    ) {
        Box(
            modifier = Modifier
                .size(40.dp)
                .clip(CircleShape)
                .background(
                    Brush.linearGradient(listOf(NearMePrimaryBlue, NearMeAccentPurple))
                ),
            contentAlignment = Alignment.Center
        ) {
            Icon(icon, contentDescription = null, tint = NearMeTextMain, modifier = Modifier.size(20.dp))
        }
        Spacer(Modifier.width(12.dp))
        Column {
            Text(title, style = MaterialTheme.typography.titleSmall, color = NearMeTextMain)
            Text(subtitle, style = MaterialTheme.typography.bodySmall, color = NearMeTextSecondary)
        }
    }
}
